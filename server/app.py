@app.post("/api/documents/upload")
def upload_pdf(
    file: Annotated[UploadFile, File(description="PDF file to extract and ingest")],
    id: Annotated[str | None, Form(description="Canonical document ID generated by client")] = None,
    client_doc_id: Annotated[str | None, Form(description="Alternative canonical document ID parameter")] = None
):
    """
    Synchronous route handler executed on FastAPI's thread pool.
    Prevents long-running PDF extraction, Azure AI calls, and Blob storage I/O
    from blocking the main asyncio event loop.
    """
    if not file.filename or not file.filename.lower().endswith(".pdf"):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Only PDF files are supported"
        )

    # Client-generated canonical ID (e.g. doc_1728... or client_doc_id)
    canonical_id = id or client_doc_id or f"doc_{int(time.time() * 1000)}_{uuid.uuid4().hex[:6]}"

    blob_uploaded_by_this_req = False
    file_hash = None

    try:
        file_bytes = file.file.read()
        if not file_bytes:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Uploaded file is empty"
            )

        # 1. Compute SHA-256 checksum for instant deduplication
        file_hash = calculate_sha256(file_bytes)
        existing = get_document_by_hash(file_hash)
        if existing:
            if existing["id"] == canonical_id:
                # Same exact document session re-uploaded / retried
                existing_interactions = get_document_interactions(existing["id"])
                briefing = next((i for i in existing_interactions if i.get("type") == "briefing"), None)
                return {
                    "success": True,
                    "deduplicated": True,
                    "document": existing,
                    "briefing": briefing
                }
            else:
                # Content duplicate! Fast-clone pages & briefing under client's canonical ID
                cloned = clone_document_content(
                    source_doc_id=existing["id"],
                    target_doc_id=canonical_id,
                    filename=file.filename,
                    file_hash=file_hash,
                    file_size=len(file_bytes),
                )
                return {
                    "success": True,
                    "deduplicated": True,
                    "document": cloned["document"],
                    "briefing": cloned["briefing"]
                }

        # 2. Extract pages and text
        full_text, pages, page_count = extract_pdf_pages(file_bytes)
        if not full_text.strip():
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Could not extract readable text from PDF"
            )

        filename = file.filename

        # 3. Upload content-addressed blob to Azure Blob Storage (fatal on failure)
        try:
            blob_url = upload_document_blob(file_hash, file_bytes, filename)
            blob_uploaded_by_this_req = True
        except Exception as storage_err:
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail=f"Failed to upload document to storage: {str(storage_err)}"
            )

        # 4. Generate proactive spoken briefing via Azure AI Foundry
        briefing = generate_document_briefing(filename, full_text)

        # 5. Persist document metadata, pages, and briefing interaction to Cosmos DB
        saved = save_document_and_pages(
            doc_id=canonical_id,
            title=briefing.get("title", filename),
            source_type="pdf",
            page_count=page_count,
            pages=pages,
            briefing=briefing,
            file_hash=file_hash,
            blob_url=blob_url,
            file_size=len(file_bytes),
        )

        return {
            "success": True,
            "deduplicated": False,
            "document": saved["document"],
            "briefing": saved["briefing"]
        }

    except HTTPException:
        # Cleanup newly uploaded blob if subsequent processing failed and no other doc references it
        if blob_uploaded_by_this_req and file_hash:
            if count_documents_by_hash_cosmos(file_hash) == 0:
                delete_document_blob(file_hash)
        raise
    except Exception as e:
        if blob_uploaded_by_this_req and file_hash:
            if count_documents_by_hash_cosmos(file_hash) == 0:
                delete_document_blob(file_hash)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to process PDF: {str(e)}"
        )

@app.post("/api/documents/url")
def ingest_url(req: UrlIngestRequest):
    raw_url = req.url
    if not raw_url:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="URL is required"
        )

    if not raw_url.startswith("http://") and not raw_url.startswith("https://"):
        url = f"https://{raw_url}"
    else:
        url = raw_url

    canonical_id = req.resolved_id or f"doc_{int(time.time() * 1000)}_{uuid.uuid4().hex[:6]}"

    try:
        full_text, title = extract_url_content(url)
        if not full_text.strip():
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Could not extract readable text from URL"
            )

        pages = [{"page": 1, "text": full_text}]
        file_hash = hashlib.sha256(full_text.encode("utf-8")).hexdigest()

        # Check deduplication
        existing = get_document_by_hash(file_hash)
        if existing:
            if existing["id"] == canonical_id:
                existing_interactions = get_document_interactions(existing["id"])
                briefing = next((i for i in existing_interactions if i.get("type") == "briefing"), None)
                return {
                    "success": True,
                    "deduplicated": True,
                    "document": existing,
                    "briefing": briefing
                }
            else:
                cloned = clone_document_content(
                    source_doc_id=existing["id"],
                    target_doc_id=canonical_id,
                    filename=title,
                    file_hash=file_hash,
                    file_size=len(full_text.encode("utf-8")),
                )
                return {
                    "success": True,
                    "deduplicated": True,
                    "document": cloned["document"],
                    "briefing": cloned["briefing"]
                }

        # Generate proactive briefing
        briefing = generate_document_briefing(title, full_text)

        # Save to Cosmos DB
        saved = save_document_and_pages(
            doc_id=canonical_id,
            title=briefing.get("title", title),
            source_type="url",
            page_count=1,
            pages=pages,
            briefing=briefing,
            file_hash=file_hash,
        )

        return {
            "success": True,
            "deduplicated": False,
            "document": saved["document"],
            "briefing": saved["briefing"]
        }

    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to process URL: {str(e)}"
        )

